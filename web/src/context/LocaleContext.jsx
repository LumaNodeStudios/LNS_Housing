const flattenLocales = (obj, prefix = '') => {
  if (!obj || typeof obj !== 'object') return {};
  const result = {};
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      Object.assign(result, flattenLocales(v, key));
    } else {
      result[key] = v;
    }
  }
  return result;
};

const LocaleContext = createContext({
  locales: defaultLocales,
  t: (key, defaultVal) => defaultVal || key
});

export const LocaleProvider = ({ children }) => {
  const [locales, setLocales] = useState(defaultLocales);

  useEffect(() => {
    // Initial fetch from FiveM client
    if (window.GetParentResourceName) {
      fetch(`https://${window.GetParentResourceName()}/getLocales`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json; charset=UTF-8' },
        body: JSON.stringify({})
      })
        .then((res) => res.json())
        .then((data) => {
          if (data && typeof data === 'object') {
            const flat = flattenLocales(data);
            setLocales((prev) => ({ ...prev, ...data, ...flat }));
          }
        })
        .catch(() => { });
    }

    // NUI message listener for dynamic locale changes
    const handleMessage = (event) => {
      const { action, locales: incomingLocales } = event.data || {};
      if (action === 'setLocales' && incomingLocales && typeof incomingLocales === 'object') {
        const flat = flattenLocales(incomingLocales);
        setLocales((prev) => ({ ...prev, ...incomingLocales, ...flat }));
      }
    };

    window.addEventListener('message', handleMessage);
    return () => window.removeEventListener('message', handleMessage);
  }, []);

  const t = (key, defaultVal, params) => {
    let text = locales[key] ?? defaultLocales[key] ?? defaultVal ?? key;
    if (params !== undefined && params !== null) {
      if (Array.isArray(params)) {
        params.forEach((param) => {
          text = text.replace(/%s|%d|%\.0f|%\.1f/, param);
        });
      } else if (typeof params === 'object') {
        Object.entries(params).forEach(([paramKey, paramVal]) => {
          text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), paramVal);
        });
      } else {
        text = text.replace(/%s|%d|%\.0f|%\.1f/, params);
      }
    }
    return text;
  };

  return (
    <LocaleContext.Provider value={{ locales, t }}>
      {children}
    </LocaleContext.Provider>
  );
};

export const useLocale = () => {
  return useContext(LocaleContext);
};

export default LocaleContext;
